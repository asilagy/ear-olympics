/* The resource region: the read-only art and sound (the cast, the title and presents pictures, Dogtor, the intro music) live in
 * the FM-1's flash outside the app's image, in the region fm1-base's device/res.c manages (app.h APP_RES_BASE; fm1.toml
 * resources). app/gen_res.py packs them from app/res/eo_*.h and writes eo_res_map.h (where each array starts). The base tells us where
 * the region is (plat_res) and whether it holds THIS build's file; the arrays below then read from it in place.
 *
 * The old names (EO_CAST, EO_INTRO, EO_DOG ...) still work, so the drawing and sound code is unchanged: each is now a pointer
 * into the region instead of an array in the image. When the region is missing (an install that did not write it, a torn
 * write, another build's file) eo_res_base is 0, and eo_res_ok() says no: every drawing helper skips its art, the music
 * does not start, and the power-on movie is skipped. */
#pragma once
#include <stdint.h>
#include "plat.h"
#include "fm1_res.h"                     /* FM1B_RES_LEN: the base tool's length of the same file (generated) */
#include "eo_res_map.h"                  /* EO_RES_OFF_*, EO_RES_LEN and the sizes (generated by gen_res.py) */

_Static_assert(EO_RES_LEN == FM1B_RES_LEN, "the resource file the game was built to read is the one the base tool packed");
_Static_assert(EO_RES_LEN + 32u <= APP_RES_SECTORS * 4096u, "the art and sound fit the resource region (tools/budget.py)");

/* the region's payload, or 0 while the FM-1 does not hold this build's (read each frame: a transfer can finish while we run) */
static const uint8_t *volatile eo_res_base;
static void eo_res_refresh(void)
{
    uint32_t n = 0;
    const uint8_t *p = plat_res(&n);
    eo_res_base = (p && n == EO_RES_LEN) ? p : 0;
}
#define eo_res_ok() (eo_res_base != 0)
#define EO_RES_AT(off) (eo_res_base + (off))     /* (only after eo_res_ok(); every offset is a multiple of 4) */

#define EO_CAST_PAL ((const uint16_t(*)[16])EO_RES_AT(EO_RES_OFF_CAST_PAL))
#define EO_CAST ((const uint8_t(*)[2][EO_CAST_W * EO_CAST_H / 2])EO_RES_AT(EO_RES_OFF_CAST))
#define EO_INTRO EO_RES_AT(EO_RES_OFF_INTRO)
#define EO_PRES_PAL ((const uint16_t *)EO_RES_AT(EO_RES_OFF_PRES_PAL))
#define EO_PRES_ROW ((const uint16_t *)EO_RES_AT(EO_RES_OFF_PRES_ROW))
#define EO_PRES_RLE EO_RES_AT(EO_RES_OFF_PRES_RLE)
#define EO_TITLE_PAL ((const uint16_t *)EO_RES_AT(EO_RES_OFF_TITLE_PAL))
#define EO_TITLE_ROW ((const uint16_t *)EO_RES_AT(EO_RES_OFF_TITLE_ROW))
#define EO_TITLE_RLE EO_RES_AT(EO_RES_OFF_TITLE_RLE)
/* Van's game (not drawn yet: the game comes next): his poses and Meow's extra ones, 96 x 72 in the cast palettes (cast 2 and 10),
 * and his room, 240 x 144 in colour runs like the title pictures (colour 0 = skip). */
#define EO_VAN ((const uint8_t(*)[EO_POSE_BYTES])EO_RES_AT(EO_RES_OFF_VAN))
#define EO_MEOWX ((const uint8_t(*)[EO_POSE_BYTES])EO_RES_AT(EO_RES_OFF_MEOWX))
#define EO_ROOM_PAL ((const uint16_t *)EO_RES_AT(EO_RES_OFF_ROOM_PAL))
#define EO_ROOM_ROW ((const uint16_t *)EO_RES_AT(EO_RES_OFF_ROOM_ROW))
#define EO_ROOM_RLE EO_RES_AT(EO_RES_OFF_ROOM_RLE)
#define EO_DOG ((const char(*)[EO_DOG_H][EO_DOG_W + 1])EO_RES_AT(EO_RES_OFF_DOG))

/* Chord Dogtor: the poses (the pictures are the region's EO_DOG, in this order) and the colour of each letter */
enum { DOG_IDLE, DOG_THINK, DOG_WIN, DOG_WORRY, DOG_YAWN, DOG_SHOCK, DOG_LISTEN, DOG_POSES };
_Static_assert(DOG_POSES == EO_DOG_POSES, "the poses named here are the poses in app/res/eo_dog.h");
#define EO_RGB(r, g, b) ((uint16_t)((((r) & 0xF8) << 8) | (((g) & 0xFC) << 3) | ((b) >> 3)))
static inline uint16_t eo_dog_col(char c)
{
    switch (c) {
    case 'A': return EO_RGB(11, 11, 11);
    case 'B': return EO_RGB(46, 46, 46);
    case 'C': return EO_RGB(90, 90, 90);
    case 'D': return EO_RGB(184, 184, 184);
    case 'E': return EO_RGB(255, 255, 255);
    case 'F': return EO_RGB(44, 62, 153);
    case 'G': return EO_RGB(143, 180, 255);
    case 'H': return EO_RGB(214, 214, 214);
    case 'I': return EO_RGB(244, 162, 89);
    case 'J': return EO_RGB(139, 76, 50);
    default: return EO_RGB(0, 0, 0);
    }
}
