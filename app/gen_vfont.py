"""Van's dialogue font: Barlow Semi Condensed SemiBold at 19 px, every printable character (lower case too), between
fm1-base's S (16 px) and M (24 px). Uses fm1-base's own renderer (tools/gen_font.py) and writes the same glyph format
as its untrimmed, unpacked faces, as FONT_V in {gen}/eo_font_v.h. The build runs this (fm1.toml gen)."""
import os
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE.parent / "base" / "tools"))
os.environ["X0X_FONTSET"] = "barlow"
os.environ["FM1_FONT_TRIM"] = ""
os.environ["FM1_FONT_PACK"] = ""
import gen_font as g  # noqa: E402

PX, FIRST, LAST = 19, 32, 126


def main(out):
    h, glyphs = g.render("BarlowSemiCondensed-SemiBold.ttf", PX, 1, False, FIRST, LAST)
    data, offs, bws = [], [], []
    for adv, bw, gl in glyphs:
        offs.append(len(data))
        bws.append(bw)
        for y in range(h):
            row = gl[y * bw:(y + 1) * bw] + [0]
            for x in range(0, bw, 2):
                data.append((row[x] << 4) | row[x + 1])
    assert len(data) < 65536
    lines = [f"/* generated by gen_vfont.py: Van's dialogue font, Barlow Semi Condensed SemiBold {PX} px, {FIRST}..{LAST} */",
             "#pragma once", "#include <stdint.h>", f"static const uint8_t FONT_V_DATA[{len(data)}] = {{"]
    for i in range(0, len(data), 24):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in data[i:i + 24]) + ",")
    lines += ["};",
              f"static const uint16_t FONT_V_OFF[{len(offs)}] = {{" + ", ".join(map(str, offs)) + "};",
              f"static const uint8_t FONT_V_ADV[{len(glyphs)}] = {{" + ", ".join(str(a) for a, _, _ in glyphs) + "};",
              f"static const uint8_t FONT_V_BW[{len(glyphs)}] = {{" + ", ".join(map(str, bws)) + "};",
              f"static const felucca_font_t FONT_V = {{ {h}, {g.PAD}, {FIRST}, {LAST}, FONT_V_ADV, FONT_V_BW, FONT_V_OFF, FONT_V_DATA }};", ""]
    Path(out).write_text("\n".join(lines))
    print(f"font V: Barlow SemiBold {PX}px h {h}, {len(data)} B")


if __name__ == "__main__":
    main(Path(sys.argv[1]) / "eo_font_v.h")
