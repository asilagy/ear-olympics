"""Draws Ear Olympics' cat (an original orange tabby with headphones) as a small pixel bitmap and writes
app/eo_cat.h. The face (eyes, mouth) is drawn by the app, so it can change; this is the head, ears, headphones, fur.
    python3 tests/gen_cat.py           # writes app/eo_cat.h and app/build/cat_preview.png (if PIL is installed)
"""
import math
import os

W, H = 28, 26
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))


def inside_tri(px, py, a, b, c):
    def sgn(p1, p2, p3):
        return (p1[0] - p3[0]) * (p2[1] - p3[1]) - (p2[0] - p3[0]) * (p1[1] - p3[1])
    p = (px, py)
    d1, d2, d3 = sgn(p, a, b), sgn(p, b, c), sgn(p, c, a)
    neg = d1 < 0 or d2 < 0 or d3 < 0
    pos = d1 > 0 or d2 > 0 or d3 > 0
    return not (neg and pos)


def ell(px, py, cx, cy, rx, ry):
    return ((px - cx) / rx) ** 2 + ((py - cy) / ry) ** 2 <= 1.0


g = [["." for _ in range(W)] for _ in range(H)]
fill = [[False] * W for _ in range(H)]
for y in range(H):
    for x in range(W):
        px, py = x + 0.5, y + 0.5
        head = ell(px, py, 14, 15.5, 10.6, 8.6)
        ear_l = inside_tri(px, py, (3.6, 13), (4.4, 1.2), (13.2, 8.4))
        ear_r = inside_tri(px, py, (24.4, 13), (23.6, 1.2), (14.8, 8.4))
        if head or ear_l or ear_r:
            fill[y][x] = True
            g[y][x] = "o"
        # a darker shade low on the cheeks and along the ear edges
        # inner ears
        if inside_tri(px, py, (5.6, 11), (5.8, 4.6), (10.6, 8.9)) or inside_tri(px, py, (22.4, 11), (22.2, 4.6), (17.4, 8.9)):
            g[y][x] = "e"
        # cream muzzle
        if ell(px, py, 14, 19.8, 4.8, 2.9):
            g[y][x] = "c"
        # tabby stripes on the forehead
        if x in (11, 14, 16) and 8 <= y <= (11 if x == 14 else 10):
            g[y][x] = "d"
        if x in (13,) and 8 <= y <= 9:
            g[y][x] = "d"
# the headphones: a cup on each side of the head, with a darker shade on the outer edge and a thin band stub
cups = [(1, 11, 4, 10), (23, 11, 4, 10)]
for (cx, cy, cw, ch) in cups:
    for y in range(cy, cy + ch):
        for x in range(cx, cx + cw):
            if (x in (cx, cx + cw - 1)) and (y in (cy, cy + ch - 1)):
                continue
            fill[y][x] = True
            outer = x == cx if cx < 10 else x == cx + cw - 1
            g[y][x] = "q" if (outer or y >= cy + ch - 2) else "p"
for x in (3, 24):                          # the band: a short stub rising from each cup along the ear
    for y in (8, 9, 10):
        fill[y][x] = True
        g[y][x] = "p"
# outline: any empty pixel next to a filled one
out = [row[:] for row in g]
for y in range(H):
    for x in range(W):
        if not fill[y][x]:
            for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
                nx, ny = x + dx, y + dy
                if 0 <= nx < W and 0 <= ny < H and fill[ny][nx]:
                    out[y][x] = "k"
                    break
rows = ["".join(r) for r in out]
# the nose
rows = [list(r) for r in rows]
rows[17][13] = "n"
rows[17][14] = "n"
rows = ["".join(r) for r in rows]

with open(os.path.join(ROOT, "app", "eo_cat.h"), "w") as f:
    f.write("/* SPDX-License-Identifier: MPL-2.0\n * Copyright (C) 2026 asilagy */\n")
    f.write("/* Generated by tests/gen_cat.py: the cat's head, ears, headphones and fur, one char per pixel.\n")
    f.write(" * . clear  k outline  o orange  d dark orange  c cream  e inner ear  p pink  q dark pink  n nose */\n")
    f.write("#pragma once\n#define EO_CAT_W %d\n#define EO_CAT_H %d\n" % (W, H))
    f.write("static const char EO_CAT[EO_CAT_H][EO_CAT_W + 1] = {\n")
    for r in rows:
        f.write('    "%s",\n' % r)
    f.write("};\n")
print("\n".join(rows))
try:
    from PIL import Image
    pal = {".": (20, 20, 24), "k": (10, 10, 12), "o": (246, 152, 56), "d": (184, 100, 28), "c": (248, 234, 214),
           "e": (240, 176, 160), "p": (238, 130, 222), "q": (176, 84, 168), "n": (120, 60, 70)}
    S = 12
    im = Image.new("RGB", (W * S, H * S))
    for y, r in enumerate(rows):
        for x, ch in enumerate(r):
            for yy in range(S):
                for xx in range(S):
                    im.putpixel((x * S + xx, y * S + yy), pal[ch])
    os.makedirs(os.path.join(ROOT, "app", "build"), exist_ok=True)
    im.save(os.path.join(ROOT, "app", "build", "cat_preview.png"))
except ImportError:
    pass
