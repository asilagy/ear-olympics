"""Makes app/res/eo_van.h: Van's seven poses, Meow's four extra poses and Van's room, from the GPT art sheets.

    python3 tests/gen_van.py VAN_A.png VAN_B.png MEOW.png ROOM.png

VAN_A / VAN_B / MEOW are 2 x 2 sheets of poses on magenta; ROOM is the wide room picture. Poses are 96 x 72, 4 bits a pixel,
and use the cast's EXISTING palettes (Van = cast 2, Meow = cast 10), so they cost no palette bytes and match the intro sprites.
The room is 240 x 144, flattened to 12 colours and run-length coded by row exactly like the title pictures: (colour, run) byte
pairs, colour 0 = skip. Needs Pillow and numpy (a build-time tool; the device never runs it)."""
import re
import sys
from collections import Counter
from pathlib import Path

import numpy as np
from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[1]
W, H = 96, 72
VAN_POSES = [("A", 0, "talking"), ("A", 1, "laughing"), ("A", 2, "cooked"), ("A", 3, "tape measure"),
             ("B", 0, "snacking"), ("B", 1, "on the phone"), ("B", 3, "asleep")]
MEOW_POSES = [(0, "asleep"), (1, "meowing"), (2, "knocking the mug"), (3, "sitting")]


def rgb(v):
    return ((v >> 11) & 31) * 255 // 31, ((v >> 5) & 63) * 255 // 63, (v & 31) * 255 // 31


def cast_palette(i):
    t = (ROOT / "app/res/eo_cast.h").read_text()
    pal = re.findall(r"\{(0x[0-9A-F]{4}(?:,0x[0-9A-F]{4}){15})\}", t)[i]
    return np.array([rgb(int(x, 16)) for x in pal.split(",")])


def pose(sheet, cell, pal):
    w, h = sheet.size
    c = sheet.crop(((cell % 2) * w // 2 + 14, (cell // 2) * h // 2 + 14, (cell % 2 + 1) * w // 2 - 14, (cell // 2 + 1) * h // 2 - 14))
    a = np.array(c).astype(int)
    magenta = (a[..., 0] > 200) & (a[..., 1] < 90) & (a[..., 2] > 200)
    clear = np.array(Image.fromarray((magenta * 255).astype("uint8")).resize((W, H), Image.BILINEAR)) > 128
    d = np.array(c.resize((W, H), Image.LANCZOS)).astype(int)
    idx = ((d[:, :, None, :] - pal[None, None, 1:, :]) ** 2).sum(-1).argmin(-1) + 1     # the nearest of colours 1..15
    idx[clear] = 0
    flat = idx.flatten()
    return bytes((int(flat[i]) << 4) | int(flat[i + 1]) for i in range(0, W * H, 2))      # high nibble first, as the cast


def room(path):
    r = Image.open(path).convert("RGB").resize((240, 144), Image.LANCZOS).filter(ImageFilter.MedianFilter(3))
    q = r.quantize(12, method=Image.MEDIANCUT, dither=Image.NONE)
    a = np.array(q)
    pal = np.array(q.getpalette()[:36]).reshape(12, 3)
    out = a.copy()
    for y in range(1, 143):                                  # clear single stray pixels
        for x in range(1, 239):
            n = [a[y - 1, x], a[y + 1, x], a[y, x - 1], a[y, x + 1]]
            v, k = Counter(n).most_common(1)[0]
            if a[y, x] not in n and k >= 3:
                out[y, x] = v
    rle, rows = bytearray(), [0]
    for row in out:
        x = 0
        while x < 240:
            j = x
            while j < 240 and row[j] == row[x]:
                j += 1
            rle += bytes([int(row[x]) + 1, j - x])          # colour 0 is "skip", so the palette starts at 1
            x = j
        rows.append(len(rle))
    p565 = [0] + [((int(r_) & 0xF8) << 8) | ((int(g) & 0xFC) << 3) | (int(b) >> 3) for r_, g, b in pal] + [0, 0, 0]
    return p565, rows, bytes(rle)


def carr(name, ctype, vals, per=16):
    body = ",\n".join("  " + ",".join(str(v) for v in vals[i:i + per]) for i in range(0, len(vals), per))
    return f"static const {ctype} {name}[{len(vals)}] = {{\n{body}\n}};\n"


def main(argv):
    if len(argv) != 5:
        print(__doc__)
        return 2
    a_, b_, m_, room_ = argv[1:]
    sheets = {"A": Image.open(a_).convert("RGB"), "B": Image.open(b_).convert("RGB")}
    vp, mp = cast_palette(2), cast_palette(10)
    van = [pose(sheets[s], c, vp) for s, c, _ in VAN_POSES]
    msheet = Image.open(m_).convert("RGB")
    meow = [pose(msheet, c, mp) for c, _ in MEOW_POSES]
    p565, rows, rle = room(room_)
    o = ["/* SPDX-License-Identifier: MPL-2.0 */",
         "/* RESOURCE SOURCE: not compiled into the app; app/gen_res.py packs it into the resource region (see app/eo_res.h). */",
         "/* Van's room scene. Generated by tests/gen_van.py from the GPT art sheets (not kept in the repo). */",
         f"#define EO_VAN_N {len(van)}                 /* " + ", ".join(n for _, _, n in VAN_POSES) + " */",
         f"#define EO_MEOWX_N {len(meow)}               /* " + ", ".join(n for _, n in MEOW_POSES) + " */",
         f"#define EO_POSE_BYTES {W * H // 2}            /* 96 x 72, 4 bits a pixel, in the cast's palette (Van: cast 2, Meow: cast 10) */",
         "#define EO_ROOM_ROWS 144                 /* the room is 240 x 144, run-length coded by row like the title pictures */",
         "static const uint8_t EO_VAN[EO_VAN_N][EO_POSE_BYTES] = {"]
    for i, d in enumerate(van):
        o.append(" {" + ",".join(str(x) for x in d) + "}" + ("," if i < len(van) - 1 else ""))
    o += ["};", "static const uint8_t EO_MEOWX[EO_MEOWX_N][EO_POSE_BYTES] = {"]
    for i, d in enumerate(meow):
        o.append(" {" + ",".join(str(x) for x in d) + "}" + ("," if i < len(meow) - 1 else ""))
    o += ["};", "/* the room: colour 0 is skip, colours 1..12 are this palette */",
          "static const uint16_t EO_ROOM_PAL[16] = {" + ",".join(f"0x{v:04X}" for v in p565) + "};",
          "static const uint16_t EO_ROOM_ROW[EO_ROOM_ROWS + 1] = {" + ",".join(str(x) for x in rows) + "};",
          f"static const uint8_t EO_ROOM_RLE[{len(rle)}] = {{" + ",".join(str(x) for x in rle) + "};", ""]
    (ROOT / "app/res/eo_van.h").write_text("\n".join(o))
    print(f"gen_van  {len(van)} Van poses, {len(meow)} Meow poses, room {len(rle)} B + {len(rows) * 2} B of rows")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
